class Command(BaseCommand):
    help = "Seed four original public guides, preserving existing articles."

    def handle(self, *args, **options):
        count = 0
        for slug, title, summary, category, sections in GUIDES:
            _, created = Article.objects.get_or_create(
                slug=slug,
                defaults={
                    "title": title,
                    "summary": summary,
                    "category": category,
                    "body": "\n\n".join(
                        "## " + heading + "\n" + body for heading, body in sections
                    ),
                    "status": "published",
                    "published_at": timezone.now(),
                },
            )
            count += created
        self.stdout.write(
            f"Created {count} guides; existing editorial content preserved."
        )
